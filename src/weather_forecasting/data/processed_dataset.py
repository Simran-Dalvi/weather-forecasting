"""
processed_dataset.py

Maintains the master processed dataset located at:
data/processed/processed.csv

The processed dataset contains:
    - Original weather variable from the raw dataset.
    - All engineered features generated by different feature pipelines.

Each feature pipeline should return only:
    date + newly created feature columns
When updating:
    - Existing feature column are replaced with newly generated values.
    - All other columns are preserved.
"""
from pathlib import Path
import pandas as pd
from weather_forecasting.utils.logger import logger
from weather_forecasting.config.paths import PROCESSED_PATH


def update_processed_dataset(
        new_features: pd.DataFrame,
        raw_df: pd.DataFrame | None = None,
        feature_store_path: Path =PROCESSED_PATH,
)-> pd.DataFrame:
    """
    Create or update the master processed dataset.

    On the first run:
        - Merges the raw dataset with the newly engineered features.
        - Saves the result as processed.csv

    On subsequent runs:
        - Loads the existing processed dataset.
        - Replaces any feature columns that already exist.
        - Adds newly engineered feature columns.
        - Preserves all other columns.

    Parameters
    ----------
    new_features: pd.DataFrame
        DataFrame containing:
            date
            feature_1
            feature_2
            ...
    raw_df : pd.DataFrame, Optional
        Original raw weather dataset.
        Required only when creating processed.csv for the first time.

    feature_store_path : Path
        Location of the master feature CSV.
    
    Returns
    -------
    pd.DataFrame
        Updated processed dataset.
    """
    # Check for date first
    if ("date") not in new_features.columns:
        raise ValueError("'date' column is required in new_features.")
    
    new_features = new_features.copy()
    new_features["date"] = pd.to_datetime(new_features["date"])

    # First time creation
    if not feature_store_path.exists():
        # work with raw df first
        if raw_df is None:
            raise ValueError(
                "raw_df MUST be provided when creating processed.csv for the FIRST time."
            )
        raw_df = raw_df.copy()

        logger.info("The latest weather data was found and copied into raw_df")

        if "date" not in raw_df.columns:
            raise ValueError("'data' column is required in raw_df.")
        
        raw_df['date'] = pd.to_datetime(raw_df['date'])

        processed_df = raw_df.merge(
            new_features,
            on='date',
            how='left',
        )
        feature_store_path.parent.mkdir(parents = True, exist_ok= True)

        processed_df.sort_values("date").to_csv(feature_store_path, index = False,)

        logger.info(
            f"Created processed dataset: {feature_store_path}"
        )

        return processed_df
    
    # Load existing processed dataset
    processed_df = pd.read_csv(feature_store_path)
    processed_df["date"] = pd.to_datetime(processed_df["date"])

    # Remove columns that will be updated
    columns_to_replace = [
        col
        for col in new_features.columns
        if col != "date" and col in processed_df.columns
    ]
    processed_df = processed_df.drop(columns = columns_to_replace)

    # Merge
    processed_df = processed_df.merge(
        new_features,
        on = "date",
        how = "left",
    )

    processed_df = processed_df.sort_values("date")

    processed_df.to_csv(
        feature_store_path,
        index = False,
    )

    logger.info(
        f"Feature store updated"
        f"({len(new_features.columns)-1} feature columns processed)"
    )

    return processed_df

def load_processed_dataset(
        feature_store_path: Path =PROCESSED_PATH,
)-> pd.DataFrame:
    """
    Load the master processed dataset.

    Parameters
    ----------
    feature_store_path : Path
        Location of processed.csv

    Returns
    -------
    pd.DataFrame
        The processed dataset contaiing both raw variables and engineered features
    """
    if not feature_store_path.exists():
        raise FileNotFoundError(
            f"No dataset found at {feature_store_path}"
        )
    df = pd.read_csv(feature_store_path)
    df["date"] = pd.to_datetime(df["date"])

    return df

def save_processed_data(
        df: pd.DataFrame,
        feature_store_path: Path =PROCESSED_PATH,
) -> None:
    """
    Save the complete processed dataset.

    The processed dataset is rebuilt from raw data on every
    processing run rather than incrementally updated.
    """

    feature_store_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    df.to_csv(
        feature_store_path,
        index=False,
    )

    logger.info(
        f"Processed dataset saved to {feature_store_path}"
    )